#!/usr/bin/env python3
"""gen_cascade.py: OpenCV Haar cascade (XML, stump-based, upright features) -> C tables

  python sw/tools/gen_cascade.py <haarcascade_frontalface_alt.xml> sw/src/face_cascade.h

The XML comes with OpenCV (e.g. pip install opencv-python:
<site-packages>/cv2/data/haarcascade_frontalface_alt.xml). The generated header is
committed, so building the firmware does not need OpenCV.

Fixed point (see sw/src/face.c):
  weak threshold  : Q31   (t = mulh(thr, 2 * nf) = floor(thr * nf);  sum(w*rect) <= t  -> left)
  leaf values     : Q16
  stage threshold : Q16
"""
import re
import sys
import xml.etree.ElementTree as ET


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding='utf-8').read()
    m = re.search(r'<!--(.*?)-->', text, re.S)
    notice = m.group(1).rstrip() if m else ''
    root = ET.fromstring(text)
    c = root.find('cascade')
    if c.find('stageType').text != 'BOOST' or c.find('featureType').text != 'HAAR':
        raise SystemExit('not a BOOST/HAAR cascade')
    win_w, win_h = int(c.find('width').text), int(c.find('height').text)

    feats = []
    for f in c.find('features'):
        t = f.find('tilted')
        if t is not None and int(t.text) != 0:
            raise SystemExit('tilted features are not supported')
        rects = []
        for r in f.find('rects'):
            x, y, w, h, wt = r.text.split()
            if float(wt) != int(float(wt)):
                raise SystemExit('non-integer rect weight')
            rects.append((int(x), int(y), int(w), int(h), int(float(wt))))
        if not 2 <= len(rects) <= 3:
            raise SystemExit('expected 2 or 3 rects per feature')
        feats.append(rects)

    stages, weaks = [], []
    for s in c.find('stages'):
        first = len(weaks)
        for wc in s.find('weakClassifiers'):
            node = wc.find('internalNodes').text.split()
            if len(node) != 4 or node[0] != '0' or node[1] != '-1':
                raise SystemExit('only stumps (one node per weak classifier) are supported')
            leaf = [float(v) for v in wc.find('leafValues').text.split()]
            weaks.append((int(node[2]), float(node[3]), leaf[0], leaf[1]))
        stages.append((first, len(weaks) - first, float(s.find('stageThreshold').text)))

    q = lambda v, b: int(round(v * (1 << b)))
    out = []
    out.append('/* face_cascade.h: generated by sw/tools/gen_cascade.py from')
    out.append(f' *   {src.replace(chr(92), "/").split("/")[-1]}  (do not edit)')
    out.append(' *')
    out.append(' * Original notice:')
    for line in notice.splitlines():
        out.append((' * ' + line.replace('*/', '* /')).rstrip())
    out.append(' */')
    out.append('#ifndef FACE_CASCADE_H')
    out.append('#define FACE_CASCADE_H')
    out.append('')
    out.append('#include "xil_types.h"')
    out.append('')
    out.append(f'#define CASC_W        {win_w}')
    out.append(f'#define CASC_H        {win_h}')
    out.append(f'#define CASC_NSTAGES  {len(stages)}')
    out.append(f'#define CASC_NWEAK    {len(weaks)}')
    out.append('')
    out.append('struct casc_stage { u16 first, count; s32 thr; };            /* thr: Q16 */')
    out.append('struct casc_weak {')
    out.append('\ts32 thr;              /* Q31 */')
    out.append('\ts32 left, right;      /* Q16 leaf values (feature < thr -> left) */')
    out.append('\tu8  n;                /* rects (2 or 3) */')
    out.append('\tu8  x[3], y[3], w[3], h[3];')
    out.append('\ts8  wt[3];')
    out.append('};')
    out.append('')
    out.append('static const struct casc_stage casc_stages[CASC_NSTAGES] = {')
    for first, cnt, thr in stages:
        out.append(f'\t{{ {first}, {cnt}, {q(thr, 16)} }},')
    out.append('};')
    out.append('')
    out.append('static const struct casc_weak casc_weaks[CASC_NWEAK] = {')
    for fi, thr, l, r in weaks:
        rs = feats[fi] + [(0, 0, 0, 0, 0)] * (3 - len(feats[fi]))
        col = lambda k: ', '.join(str(x[k]) for x in rs)
        out.append(f'\t{{ {q(thr, 31)}, {q(l, 16)}, {q(r, 16)}, {len(feats[fi])}, '
                   f'{{ {col(0)} }}, {{ {col(1)} }}, {{ {col(2)} }}, {{ {col(3)} }}, {{ {col(4)} }} }},')
    out.append('};')
    out.append('')
    out.append('#endif')
    open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{dst}: {win_w}x{win_h}, {len(stages)} stages, {len(weaks)} weak classifiers')

    # ── optional: ROM files for the hardware engine (haar_engine.v) ──
    #   gen_cascade.py <xml> <header> <rom_dir> <n_stages>
    if len(sys.argv) > 4:
        write_rom(sys.argv[3], int(sys.argv[4]), stages, weaks, feats, q)


def write_rom(rom_dir, nst, stages, weaks, feats, q):
    """haar_weak.mem : one 128-bit word per weak classifier of the first nst stages
         [4:0] x0 [9:5] y0 [14:10] w0 [19:15] h0            rect 0 (weight -1)
         [24:20] x1 [29:25] y1 [34:30] w1 [39:35] h1 [40]   rect 1, [40] = weight 3 (else 2)
         [45:41] x2 [50:46] y2 [55:51] w2 [60:56] h2 [61]   rect 2, [61] = weight 3 (else 2)
         [62] rect 2 present
         [94:63] thr (Q31, two's complement)  [110:95] left (Q16)  [126:111] right (Q16)
       haar_stage.mem : one 48-bit word per stage  {count[15:0], thr[31:0] (Q16)}
       haar_params.vh : HAAR_NSTAGE / HAAR_NWEAK"""
    import os
    n_weak = stages[nst - 1][0] + stages[nst - 1][1]
    lines = []
    for fi, thr, l, r in weaks[:n_weak]:
        rs = feats[fi]
        if rs[0][4] != -1 or any(x[4] not in (2, 3) for x in rs[1:]):
            raise SystemExit('ROM: expected weights -1 / {2,3} / {2,3}')
        v = 0
        for k, (x, y, w, h, wt) in enumerate(rs):
            for i, f in enumerate((x, y, w, h)):
                if not 0 <= f < 32:
                    raise SystemExit('ROM: rect field out of range')
            base = (0, 20, 41)[k]
            v |= x << base | y << (base + 5) | w << (base + 10) | h << (base + 15)
            if k > 0 and wt == 3:
                v |= 1 << (base + 20)
        if len(rs) == 3:
            v |= 1 << 62
        tq, lq, rq = q(thr, 31), q(l, 16), q(r, 16)
        if not (-(1 << 31) <= tq < (1 << 31) and 0 <= lq < 65536 and 0 <= rq < 65536):
            raise SystemExit('ROM: value out of range')
        v |= (tq & 0xFFFFFFFF) << 63 | lq << 95 | rq << 111
        lines.append(f'{v:032x}')
    open(os.path.join(rom_dir, 'haar_weak.mem'), 'w', newline='\n').write('\n'.join(lines) + '\n')
    sl = []
    for first, cnt, thr in stages[:nst]:
        sl.append(f'{(cnt << 32) | (q(thr, 16) & 0xFFFFFFFF):012x}')
    open(os.path.join(rom_dir, 'haar_stage.mem'), 'w', newline='\n').write('\n'.join(sl) + '\n')
    open(os.path.join(rom_dir, 'haar_params.vh'), 'w', newline='\n').write(
        '// generated by sw/tools/gen_cascade.py (do not edit)\n'
        f'`define HAAR_NSTAGE {nst}\n`define HAAR_NWEAK {n_weak}\n')
    print(f'{rom_dir}: ROM for the first {nst} stages, {n_weak} weak classifiers')


if __name__ == '__main__':
    main()
